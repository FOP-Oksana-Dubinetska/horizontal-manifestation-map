#pragma once

// std::string - стандартный тип C++ для строки, которая владеет своими данными.
// Нам нужны строки для ID и отображаемых названий сущностей карты.
#include <optional>
#include <string>
#include <vector>
#include <cstdint>
#include <variant>

namespace roadmap
{

    // Состояние намерения.
    //
    // enum class задает закрытый набор допустимых значений.
    // В отличие от обычных строк сюда невозможно случайно записать,
    // например, "actve" вместо "active": компилятор просто не позволит
    // использовать значение, которого нет в перечислении.
    enum class IntentStatus
    {
        draft,
        active,
        implemented,
        deferred
    };

    // Характер жизненного цикла намерения.
    // 
    // finite - намерение имеет конечный результат;
    // continuous - намерение поддерживается постоянно.
    enum class IntentKind
    {
        finite,
        continuous
    };

    // Смысловая роль шага внутри маршрута.
    //
    // Во внешнем JSON позже будут строки:
    // "intent", "module", "shared", "validation", "export".
    // 
    // В C++ слово "export" является ключевым словом языка,
    // поэтому элемент перечисления нельзя назвать просто 'export'.
    // Внутри C++ используем 'exportStep', а JSON-адаптер позже 
    // будет преобразовывать его в строку "export".
    enum class StepStereotype
    {
        intent,
        module,
        shared,
        validation,
        exportStep
    };

    // Тип проектного модуля.
    // 
    // Во внешнем JSON значение export будет строкой "export".
    // В C++ слово export зарезервировано, поэтому используем exportModule.
    enum class ModuleKind
    {
        core,
        ui,
        storage,
        exportModule,
        demo,
        validation
    };

    // Состояние существующего модуля.
    // 
    // planned - модуль запланирован, но ещё не существует;
    // existing - существует;
    // deprecated - существует исторически, но больше не рекомендуется.
    enum class ModuleExistence
    {
        planned,
        existing,
        deprecated
    };

    // Один конкретный шаг внутри маршрута.
    //
    // RouteStep хранит собственные данные шага и ID связей
    // с другими сущностями проекта.
    // Связанные объекты сюда непосредственно не вкладываются.
    //
    // struct здесь удобен, потому что RouteStep пока является простой
    // структурой данных: его поля непосредственно представляют состояние
    // сущности и не требуют сложных инвариантов или сложного поведения.
    struct RouteStep
    {
        // Стабильный машинный идентификатор шага.
        // Например: "s-validation".
        std::string id;

        // Читаемое человеком название.
        // Например: "Проверить связи".
        std::string title;

        // Смысловая роль шага в маршруте.
        // Здесь хранится одно значение из StepStereotype.
        StepStereotype stereotype;

        // Ссылка на оценку.
        //
        // Оценки у шага может не быть вообще, поэтому обычная строка
        // здесь плохо выражала бы смысл: пустая строка могла бы означать
        // либо "значение отсутствует", либо "кто-то записал пустой ID".
        //
        // std::optional<std::string> выражает два состояния явно:
        // 1. строка существует;
        // 2. значения нет.
        std::optional<std::string> estimateId;

        // ID модулей, связанных с этим шагом.
        //
        // std::vector хранит последовательность значений одного типа.
        // Здесь число связанных модулей заранее неизвестно:
        // их может быть 0, 1, 2 и больше.
        std::vector<std::string> linkedModuleIds;

        // Аналогичный список связанных литературных фрагментов.
        std::vector<std::string> linkedChunkIds;
    };

    // Маршрут объединяет:
    // 
    // - собственную идентичность;
    // - ссылку на намерение через ID;
    // - читаемое название;
    // - упорядоченный набор шагов.
    struct IntentRoute
    {
        // Стабильный идентификатор маршрута.
        // Например: "r-export".
        std::string id;

        // ID намерения, которому принадлежит маршрут.
        //
        // Мы храним именно ID, а не указатель и не вложенный IntentNode.
        // Благодаря этому связи между объектами остаются явными.
        std::string intentId;

        // Название маршрута для человека.
        // Например: "Экспорт проекта".
        std::string title;

        // Последовательность шагов маршрута.
        //
        // Здесь vector впервые хранит не стандартный тип вроде string,
        // а созданный нам собственный тип RouteStep.
        std::vector<RouteStep> steps;
    };

    // Намерение описывает желаемое свойство или результат проекта.
    struct IntentNode
    {
        // Стабильная идентичность намерения.
        std::string id;

        // Короткое название для человека.
        std::string title;

        // Более подробное пояснение смысла намерения.
        //
        // Для draft оно может быть пустым.
        std::string summary;

        // Текущее состояние намерения.
        IntentStatus status;

        // Конечное это намерение или постоянно поддерживаемое.
        IntentKind kind;

        // ID намерений, из которых возникло данное намерение.
        //
        // Обратите внимание: опять храним ID, а не IntentNode внутри IntentNode.
        std::vector<std::string> parentIntentIds;

        // Текстовые критерии по которым можно понять,
        // что желаемый результат достигнут.
        std::vector<std::string> acceptanceCriteria;
    };

    // Ссылка на конкретное место в кодовой базе.
    //
    // Это только данные.
    // На данном этапе программа не обращается к Git,
    // не проверяет существование файла и не ищет symbol.
    struct CodeRef
    {
        // URL репозитория либо его явно определенное локальное имя.
        std::string repository;

        // Относительный путь внутри репозитория.
        // Во внешнем формате разделителем будет '/'.
        std::string path;

        // Конкретная ревизия может отсутствовать.
        // Например, ссылка может относиться просто к текущему состоянию проекта.
        std::optional<std::string> revision;

        // Имя класса, функции или другого символа также необязательно.
        std::optional<std::string> symbol;
    };

    // Именованный модуль проектируемой системы.
    //
    // RoadmapModule не обязан совпадать с одним C++ файлом,
    // классом или даже библиотекой.
    // Это элемент архитектурной карты.
    struct RoadmapModule
    {
        // Стабильный id модуля.
        std::string id;

        // Название для человека.
        std::string title;

        // Объяснение роли модуля.
        std::string summary;

        // Смысловая категория модуля.
        ModuleKind kind;

        // Намерения, с которыми автор явно связывает этот модуль.
        //
        // Здесь снова храним ID, а не объекты IntentNode.
        std::vector<std::string> linkedIntentIds;

        // Существует ли модуль в реализации сейчас.
        ModuleExistence existence;

        // Ноль или больше ссылок на соответствующие места в коде.
        std::vector<CodeRef> codeRefs;
    };

    // Литературный фрагмент проекта.
    //
    // LiterateChunk хранит авторский текст и его смысловые связи
    // с другими сущностями карты.
    //
    // В отличие от RouteStep, который описывает действие маршрута,
    // LiterateChunk может содержать объяснение, заметку,
    // документацию или иной текстовый материал.
    struct LiterateChunk
    {
        // Стабильный идентификатор фрагмента.
        // Например: "c-validation".
        std::string id;

        // Читаемое человеком имя фрагмента.
        // В контракте используется именно name, а не title.
        std::string name;

        // Исходный авторский текст.
        //
        // std::string хранит последовательность символов/байтов.
        // При использовании UTF-8 одна видимая буква может
        // занимать несколько байтов.
        //
        // На текущем этапе мы не разбираем Markdown
        // и не меняем содержание текста.
        std::string body;

        // ID намерений, о которых рассказывает фрагмент.
        //
        // Здесь хранятся только строковые идентификаторы,
        // а не вложенные объекты IntentNode.
        std::vector<std::string> linkedIntentIds;

        // ID архитектурных модулей, связанных с текстом.
        //
        // Один фрагмент может документировать
        // несколько разных модулей.
        std::vector<std::string> linkedModuleIds;
    };

    // Авторское пересечение элементов карты.
    //
    // RoadmapIntersection описывает общую смысловую точку
    // между двумя или более сущностями проекта.
    //
    // Пересечение не создаёт новые связи автоматически
    // и не изменяет исходные сущности.
    struct RoadmapIntersection
    {
        // Стабильный идентификатор пересечения.
        // Например: "x-validation".
        std::string id;

        // Название общей точки.
        std::string title;

        // Идентификаторы исходных элементов.
        //
        // По контракту здесь допустимы ID:
        // - намерений (IntentNode);
        // - модулей (RoadmapModule);
        // - литературных фрагментов (LiterateChunk);
        // - шагов маршрутов (RouteStep).
        //
        // Должно присутствовать минимум два различных ID.
        //
        // ID проекта, маршрута, оценки и другого пересечения
        // использовать здесь нельзя.
        //
        // Сейчас vector только хранит значения.
        // Проверка перечисленных ограничений появится
        // на отдельном этапе валидации.
        std::vector<std::string> sourceIds;

        // Авторское объяснение пересечения.
        //
        // Это текст, а не вычисленный системой результат.
        std::string note;
    };

    // Что именно измеряет числовая оценка.
    //
    // effort  — трудоёмкость в человеко-минутах;
    // elapsed — календарная длительность в минутах.
    //
    // Это разные величины: четыре часа работы двух человек
    // не обязательно означают четыре часа календарного времени.
    enum class EstimateMetric
    {
        effort,
        elapsed
    };

    // Числовая оценка в виде диапазона.
    //
    // Например: от 120 до 240 человеко-минут.
    struct EstimateRange
    {
        // Смысл измеряемой величины.
        EstimateMetric metric;

        // Минимальная оценка в минутах.
        std::int64_t minMinutes;

        // Максимальная оценка в минутах.
        std::int64_t maxMinutes;
    };

    // Неизвестная оценка.
    //
    // Здесь нет выдуманного нуля или приблизительного числа.
    // Мы явно фиксируем причину отсутствия знания.
    struct EstimateUnknown
    {
        std::string reason;
    };

    // Оценка неприменима.
    //
    // Это отличается от unknown:
    // мы не ожидаем числовой оценки в данном контексте.
    struct EstimateNotApplicable
    {
        std::string reason;
    };

    // Текстовая оценка.
    //
    // Используется для исторических и ещё не формализованных
    // авторских оценок.
    //
    // Текст сохраняется, но автоматически не пересчитывается.
    struct EstimateText
    {
        std::string text;
    };

    // Объединение четырёх взаимоисключающих форм.
    //
    // using создаёт псевдоним типа.
    //
    // EstimateValue — не новая структура с четырьмя полями.
    // Это один объект, который в каждый момент хранит
    // ровно один из указанных типов.
    using EstimateValue = std::variant<
        EstimateRange,
        EstimateUnknown,
        EstimateNotApplicable,
        EstimateText
    >;


    // Субъективная уверенность автора в оценке.
    //
    // Это не процент вероятности и не статистический
    // доверительный интервал.
    enum class EstimateConfidence
    {
        low,
        medium,
        high
    };

    // Самостоятельная запись оценки.
    //
    // EstimateEntry хранит не только значение,
    // но и идентичность, пояснение и основание.
    //
    // Одна запись может использоваться несколькими
    // шагами через их estimateId.
    struct EstimateEntry
    {
        // Стабильный ID оценки.
        // Например: "e-validation".
        std::string id;

        // Авторское название или пояснение.
        //
        // Числовое значение выводится из value,
        // а не извлекается из текста label.
        std::string label;

        // Уверенность автора.
        EstimateConfidence confidence;

        // Основание для оценки.
        //
        // Пустая строка допускается, но в дальнейшем
        // должна сопровождаться предупреждением.
        std::string basis;

        // Типизированное значение.
        //
        // Здесь мы впервые используем созданный ранее
        // std::variant как поле другой структуры.
        EstimateValue value;
    };

    // Выбранный словарь терминов для отображения проекта.
    //
    // Профиль меняет названия элементов в интерфейсе,
    // но не их идентификаторы и не предметную структуру.
    //
    // ТЗ допускает ровно четыре значения.
    enum class TerminologyProfile
    {
        engineering,
        simple,
        product,
        literary
    };

    // Метаданные канонического документа.
    //
    // Эти сведения относятся ко всему проекту,
    // а не к отдельным намерениям или модулям.
    struct RoadmapMetadata
    {
        // Версия формата документа.
        //
        // Для схемы 2 ТЗ требует строку "2.0.0".
        std::string formatVersion;

        // Момент первого сохранения проекта.
        //
        // std::nullopt означает, что дата ещё не установлена.
        //
        // В будущем время поступит от внешнего Clock.
        std::optional<std::string> createdAt;

        // Момент последнего пользовательского сохранения.
        //
        // При наличии даты ТЗ требует RFC 3339 UTC
        // с суффиксом Z.
        //
        // Пока храним дату как строку, не разбирая её.
        std::optional<std::string> updatedAt;
    };

    // Корневой объект горизонтальной карты.
    //
    // RoadmapProject объединяет все сущности проекта
    // в одной канонической модели данных.
    //
    // Каждая коллекция владеет своими объектами.
    // Связи между коллекциями представлены строковыми ID.
    struct RoadmapProject
    {
        // Версия предметной схемы.
        // Текущая схема имеет номер 2.
        int schemaVersion;

        // Стабильная идентичность проекта.
        std::string id;

        // Название проекта для человека.
        std::string title;

        // Выбранная терминология отображения.
        TerminologyProfile terminologyProfile;

        // Упорядоченный список намерений.
        std::vector<IntentNode> intents;

        // Выбранное намерение либо отсутствие выбора.
        std::optional<std::string> selectedIntentId;

        // Выбранный маршрут либо отсутствие выбора.
        std::optional<std::string> selectedRouteId;

        // Упорядоченный список маршрутов.
        std::vector<IntentRoute> routes;

        // Архитектурные модули.
        std::vector<RoadmapModule> modules;

        // Литературные фрагменты.
        std::vector<LiterateChunk> chunks;

        // Авторские пересечения элементов карты.
        std::vector<RoadmapIntersection> intersections;

        // Самостоятельные записи оценок.
        std::vector<EstimateEntry> estimates;

        // Версия формата и даты сохранения.
        RoadmapMetadata metadata;
    };
}
